interface LanguageContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

const localeChangeEvent = "classify-locale-change";

function isLocale(value: string | null): value is Locale {
  return value === "id" || value === "en" || value === "de" || value === "ja";
}

function getSavedLocale(): Locale {
  const saved = window.localStorage.getItem("classify-locale");
  return isLocale(saved) ? saved : "id";
}

function getServerLocale(): Locale {
  return "id";
}

function subscribeToLocaleChanges(onChange: () => void) {
  window.addEventListener("storage", onChange);
  window.addEventListener(localeChangeEvent, onChange);
  return () => {
    window.removeEventListener("storage", onChange);
    window.removeEventListener(localeChangeEvent, onChange);
  };
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const locale = useSyncExternalStore(subscribeToLocaleChanges, getSavedLocale, getServerLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  function setLocale(nextLocale: Locale) {
    window.localStorage.setItem("classify-locale", nextLocale);
    window.dispatchEvent(new Event(localeChangeEvent));
  }

  const value: LanguageContextValue = {
    locale,
    setLocale,
    t: (key) => (locale === "id" ? key : translations[locale][key] ?? pageTranslations[locale][key] ?? key),
  };

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider.");
  return context;
}
